val newBuildDir: Directory =
    rootProject.layout.buildDirectory
        .dir("../../build")
        .get()
rootProject.layout.buildDirectory.value(newBuildDir)

subprojects {
    val newSubprojectBuildDir: Directory = newBuildDir.dir(project.name)
    project.layout.buildDirectory.value(newSubprojectBuildDir)
}
// super_keyboard (used by super_editor) compiles against Android API 34, but
// its dependency flutter_plugin_android_lifecycle requires its users to
// compile against 36. Compiling against a newer API changes no runtime
// behavior. Drop this once super_keyboard compiles against 36.
subprojects {
    if (name == "super_keyboard") {
        afterEvaluate {
            extensions.configure<com.android.build.gradle.LibraryExtension> {
                compileSdk = 36
            }
        }
    }
}
subprojects {
    project.evaluationDependsOn(":app")
}

